-- ==============================================================================
-- Thinkatic Enterprise Database Schema Migration for Supabase
-- Tables:
--   1. admin_users          (Admin authentication & permissions)
--   2. profiles             (User accounts & authentication profiles)
--   3. contact_submissions  (Leads & inquiries management)
--   4. plans                (Enterprise technology service packages)
--   5. attendance           (User check-in/out attendance tracking)
--   6. kyc_verifications    (Identity KYC verification flow)
--   7. affiliate_referrals  (Affiliate program, referral links & commission)
--   8. wallets              (User wallet balances & accounts)
--   9. wallet_transactions  (Transaction ledger & payout history)
--  10. client_updates       (Private client-specific project communication)
-- Includes: Triggers, Foreign Keys, Indexes, RLS Policies, Seed Data
-- ==============================================================================

-- 1. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 2. TRIGGER FUNCTION FOR updated_at
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ------------------------------------------------------------------------------
-- 1. Table: admin_users
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

DROP TRIGGER IF EXISTS trg_admin_users_updated_at ON public.admin_users;
CREATE TRIGGER trg_admin_users_updated_at
    BEFORE UPDATE ON public.admin_users
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

