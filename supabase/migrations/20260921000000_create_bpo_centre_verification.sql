-- 3. BPO Centre Media Evidence Table (Categorized Photos & Live Video)
CREATE TABLE IF NOT EXISTS public.bpo_centre_media (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  verification_id BIGINT NOT NULL REFERENCES public.bpo_centre_verification(id) ON DELETE CASCADE,
  partner_id UUID REFERENCES public.bpo_partners(id) ON DELETE SET NULL,
  applicant_user_id TEXT NOT NULL,
  centre_id TEXT,

  media_type TEXT NOT NULL CHECK (media_type IN ('photo', 'video')),
  category TEXT NOT NULL, -- reception_entrance, workstation_area, operations_area, management_area, infrastructure_equipment, network_setup, power_backup, security_access, live_walkthrough
  storage_key TEXT NOT NULL, -- relative private path: bpo/centre-verification/{partnerId}/{verificationId}/...
  original_file_name TEXT NOT NULL,
  mime_type TEXT NOT NULL,
  file_size INTEGER NOT NULL,
  duration_seconds INTEGER, -- for video
  uploaded_by TEXT NOT NULL,
  uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived', 'superseded'))
);

CREATE INDEX IF NOT EXISTS idx_bpo_centre_media_verif ON public.bpo_centre_media(verification_id);
CREATE INDEX IF NOT EXISTS idx_bpo_centre_media_type ON public.bpo_centre_media(media_type);
CREATE INDEX IF NOT EXISTS idx_bpo_centre_media_cat ON public.bpo_centre_media(category);
CREATE INDEX IF NOT EXISTS idx_bpo_centre_media_user ON public.bpo_centre_media(applicant_user_id);

-- 4. BPO Centre Verification History (Preserves previous submissions & audit transitions)
CREATE TABLE IF NOT EXISTS public.bpo_centre_verification_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  verification_id BIGINT NOT NULL REFERENCES public.bpo_centre_verification(id) ON DELETE CASCADE,
  submission_round INTEGER NOT NULL DEFAULT 1,
  action TEXT NOT NULL, -- created, details_updated, photo_uploaded, video_uploaded, submitted, under_review, approved, rejected, resubmitted
  from_status TEXT,
  to_status TEXT NOT NULL,
  actor_id TEXT NOT NULL,
  actor_role TEXT NOT NULL DEFAULT 'partner', -- partner, admin, system
  actor_name TEXT,
  notes TEXT,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_bpo_centre_verif_hist_verif ON public.bpo_centre_verification_history(verification_id);

