-- 2. BPO Centre Verification Table
CREATE TABLE IF NOT EXISTS public.bpo_centre_verification (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id UUID REFERENCES public.bpo_partners(id) ON DELETE SET NULL,
  application_id BIGINT REFERENCES public.bpo_partner_applications(id) ON DELETE SET NULL,
  centre_id TEXT, -- Populated if Centre ID already issued
  applicant_user_id TEXT NOT NULL,

  -- Office / Centre Attributes
  office_name TEXT NOT NULL,
  address_line_1 TEXT NOT NULL,
  address_line_2 TEXT,
  city TEXT NOT NULL,
  state TEXT NOT NULL,
  country TEXT NOT NULL DEFAULT 'India',
  postal_code TEXT NOT NULL,
  landmark TEXT,
  contact_number TEXT NOT NULL,
  centre_type TEXT NOT NULL DEFAULT 'Dedicated BPO Facility', -- e.g. Dedicated BPO Facility, Corporate Branch, Technology Park, Co-working Floor
  ownership_type TEXT NOT NULL DEFAULT 'Commercial Lease', -- e.g. Owned, Commercial Lease, Rented, Operational Agreement
  operating_since TEXT NOT NULL,
  total_area_sqft NUMERIC(10,2),
  number_of_floors INTEGER DEFAULT 1,

  -- Verification Lifecycle Status
  status TEXT NOT NULL DEFAULT 'NOT_STARTED'
    CHECK (status IN (
      'NOT_STARTED',
      'IN_PROGRESS',
      'SUBMITTED',
      'UNDER_REVIEW',
      'APPROVED',
      'REJECTED',
      'RESUBMISSION_REQUIRED'
    )),

  -- Timestamps & Submissions
  submitted_at TIMESTAMPTZ,
  submission_count INTEGER NOT NULL DEFAULT 0,

  -- Human Admin Review
  reviewed_at TIMESTAMPTZ,
  reviewed_by_admin_id BIGINT,
  reviewed_by_admin_name TEXT,
  rejection_reason TEXT,

  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

