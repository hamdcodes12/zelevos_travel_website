  FOREACH table_name IN ARRAY ARRAY['meetings','meeting_participants','meeting_requests','meeting_notes','meeting_action_items','meeting_reminders'] LOOP
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', table_name || ' service role access', table_name);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR ALL TO service_role USING (true) WITH CHECK (true)', table_name || ' service role access', table_name);
  END LOOP;
END $$;
