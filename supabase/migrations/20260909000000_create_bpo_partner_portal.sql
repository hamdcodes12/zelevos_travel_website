CREATE TABLE IF NOT EXISTS public.bpo_partner_user_permissions (
  partner_user_id BIGINT NOT NULL REFERENCES public.bpo_partner_users(id) ON DELETE CASCADE,
  permission_key TEXT NOT NULL REFERENCES public.bpo_permissions(permission_key) ON DELETE CASCADE,
  PRIMARY KEY (partner_user_id, permission_key)
);

CREATE TABLE IF NOT EXISTS public.bpo_centres (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id UUID NOT NULL REFERENCES public.bpo_partners(id) ON DELETE CASCADE,
  name TEXT NOT NULL CHECK (char_length(name) BETWEEN 2 AND 200),
  location TEXT,
  contact_name TEXT,
  contact_phone TEXT,
  email TEXT,
  capacity INTEGER NOT NULL DEFAULT 0 CHECK (capacity >= 0),
  operating_hours TEXT,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','suspended')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.bpo_partner_projects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id UUID NOT NULL REFERENCES public.bpo_partners(id) ON DELETE CASCADE,
  project_id BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  centre_id BIGINT REFERENCES public.bpo_centres(id) ON DELETE SET NULL,
  campaign_name TEXT,
  target TEXT,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','completed','suspended')),
  assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (partner_id, project_id)
);

CREATE TABLE IF NOT EXISTS public.bpo_agents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id UUID NOT NULL REFERENCES public.bpo_partners(id) ON DELETE CASCADE,
  centre_id BIGINT REFERENCES public.bpo_centres(id) ON DELETE SET NULL,
  profile_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  employee_id TEXT NOT NULL,
  name TEXT NOT NULL,
  email TEXT,
  phone TEXT,
  agent_role TEXT NOT NULL DEFAULT 'agent',
  joining_date DATE,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','on_leave','suspended')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (partner_id, employee_id)
);

CREATE TABLE IF NOT EXISTS public.bpo_agent_assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agent_id BIGINT NOT NULL REFERENCES public.bpo_agents(id) ON DELETE CASCADE,
  partner_project_id BIGINT NOT NULL REFERENCES public.bpo_partner_projects(id) ON DELETE CASCADE,
  assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  unassigned_at TIMESTAMPTZ,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (agent_id, partner_project_id)
);

CREATE INDEX IF NOT EXISTS idx_bpo_partner_users_user ON public.bpo_partner_users(user_id);
CREATE INDEX IF NOT EXISTS idx_bpo_centres_partner ON public.bpo_centres(partner_id);
CREATE INDEX IF NOT EXISTS idx_bpo_partner_projects_partner ON public.bpo_partner_projects(partner_id);
CREATE INDEX IF NOT EXISTS idx_bpo_partner_projects_project ON public.bpo_partner_projects(project_id);
CREATE INDEX IF NOT EXISTS idx_bpo_agents_partner ON public.bpo_agents(partner_id);
CREATE INDEX IF NOT EXISTS idx_bpo_agents_centre ON public.bpo_agents(centre_id);
CREATE INDEX IF NOT EXISTS idx_bpo_assignments_project ON public.bpo_agent_assignments(partner_project_id);

DROP TRIGGER IF EXISTS trg_bpo_partners_updated_at ON public.bpo_partners;
