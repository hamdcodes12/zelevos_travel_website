-- Additive BPO partner operations model. No client financial data is copied here.
INSERT INTO public.module_settings (module_key, enabled)
VALUES ('bpo_partner_portal', TRUE), ('partner_centres', TRUE), ('partner_projects', TRUE), ('partner_agents', TRUE), ('partner_attendance', TRUE), ('partner_reports', TRUE)
ON CONFLICT (module_key) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.bpo_partners (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  partner_code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL CHECK (char_length(name) BETWEEN 2 AND 200),
  legal_name TEXT,
  contact_name TEXT,
  email TEXT,
  phone TEXT,
  address TEXT,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','suspended')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.bpo_partner_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id UUID NOT NULL REFERENCES public.bpo_partners(id) ON DELETE CASCADE,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  role TEXT NOT NULL DEFAULT 'partner_admin' CHECK (role IN ('partner_admin','operations_manager','centre_manager','team_leader','agent')),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','suspended')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (partner_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.bpo_permissions (
  permission_key TEXT PRIMARY KEY,
  description TEXT NOT NULL
);
