CREATE TRIGGER trg_bpo_centres_updated_at BEFORE UPDATE ON public.bpo_centres FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
DROP TRIGGER IF EXISTS trg_bpo_agents_updated_at ON public.bpo_agents;
CREATE TRIGGER trg_bpo_agents_updated_at BEFORE UPDATE ON public.bpo_agents FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

