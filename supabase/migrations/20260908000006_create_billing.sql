-- ---------------------------------------------------------------------------
-- Sequential invoice number generator
-- Produces numbers like INV-2026-000001
-- ---------------------------------------------------------------------------
CREATE SEQUENCE IF NOT EXISTS public.invoice_number_seq
    START WITH 1
    INCREMENT BY 1
    NO MAXVALUE
    NO CYCLE;

-- Function to generate the formatted invoice number
CREATE OR REPLACE FUNCTION public.next_invoice_number()
RETURNS TEXT
LANGUAGE plpgsql
AS $$
DECLARE
    seq_val BIGINT;
    year_part TEXT;
BEGIN
    seq_val := nextval('public.invoice_number_seq');
    year_part := to_char(NOW() AT TIME ZONE 'UTC', 'YYYY');
    RETURN 'INV-' || year_part || '-' || lpad(seq_val::TEXT, 6, '0');
END;
$$;

-- ---------------------------------------------------------------------------
-- Table: invoices
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.invoices (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number      TEXT NOT NULL UNIQUE DEFAULT public.next_invoice_number(),
    client_id           UUID NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
    project_id          BIGINT REFERENCES public.projects(id) ON DELETE SET NULL,
    related_ticket_id   BIGINT REFERENCES public.tickets(id) ON DELETE SET NULL,
    purchase_id         BIGINT REFERENCES public.purchases(id) ON DELETE SET NULL,

    -- Lifecycle: draft → sent → pending_payment → paid | partially_paid → paid
    status              TEXT NOT NULL DEFAULT 'draft'
                            CHECK (status IN (
                                'draft', 'sent', 'pending_payment',
                                'partially_paid', 'paid', 'overdue',
                                'cancelled', 'refunded'
                            )),

    -- Dates
    invoice_date        DATE NOT NULL DEFAULT CURRENT_DATE,
    due_date            DATE NOT NULL,

    -- Amounts — always server-calculated, never trusted from client
    currency            TEXT NOT NULL DEFAULT 'USD',
    subtotal            NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    tax_rate            NUMERIC(6,4) NOT NULL DEFAULT 0 CHECK (tax_rate >= 0 AND tax_rate <= 1),
    tax_amount          NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
    discount_amount     NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    total               NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    amount_paid         NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (amount_paid >= 0),
    balance_due         NUMERIC(14,2) GENERATED ALWAYS AS (total - amount_paid) STORED,

    -- Metadata
    notes               TEXT,
    terms               TEXT,
    internal_notes      TEXT,   -- admin-only, never exposed to client
    sent_at             TIMESTAMPTZ,
    paid_at             TIMESTAMPTZ,
    cancelled_at        TIMESTAMPTZ,
    cancellation_reason TEXT,

    -- Admin who created / last modified
    created_by_admin_id BIGINT REFERENCES public.admin_users(id) ON DELETE SET NULL,
    updated_by_admin_id BIGINT REFERENCES public.admin_users(id) ON DELETE SET NULL,

    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT invoice_due_date_order CHECK (due_date >= invoice_date),
    CONSTRAINT invoice_paid_not_exceed_total CHECK (amount_paid <= total)
);

-- ---------------------------------------------------------------------------
-- Table: invoice_items  (line items)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.invoice_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id      BIGINT NOT NULL REFERENCES public.invoices(id) ON DELETE CASCADE,
    sort_order      INTEGER NOT NULL DEFAULT 0,
    description     TEXT NOT NULL CHECK (char_length(description) BETWEEN 1 AND 500),
    quantity        NUMERIC(10,3) NOT NULL DEFAULT 1 CHECK (quantity > 0),
    unit_price      NUMERIC(14,2) NOT NULL CHECK (unit_price >= 0),
    -- line_total = quantity * unit_price (stored for performance, recalculated on save)
    line_total      NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (line_total >= 0),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------------
-- Table: invoice_payments  (individual payment transactions against an invoice)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.invoice_payments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id          BIGINT NOT NULL REFERENCES public.invoices(id) ON DELETE RESTRICT,
    client_id           UUID NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,

    amount              NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    currency            TEXT NOT NULL DEFAULT 'USD',

    -- Payment method
    payment_method      TEXT NOT NULL DEFAULT 'manual'
                            CHECK (payment_method IN ('paypal', 'manual', 'bank_transfer', 'wallet', 'other')),
    gateway             TEXT,           -- 'paypal', null for manual
    gateway_order_id    TEXT UNIQUE,    -- PayPal orderId — unique to prevent duplicates
    gateway_capture_id  TEXT UNIQUE,    -- PayPal captureId
    reference           TEXT,           -- Manual reference number / bank reference

    -- Status
    status              TEXT NOT NULL DEFAULT 'initiated'
                            CHECK (status IN (
                                'initiated', 'pending', 'successful',
                                'failed', 'cancelled', 'refunded'
                            )),

    -- Who recorded it (for manual payments)
    recorded_by_admin_id BIGINT REFERENCES public.admin_users(id) ON DELETE SET NULL,

    paid_at             TIMESTAMPTZ,
    notes               TEXT,
    metadata            JSONB NOT NULL DEFAULT '{}'::jsonb,

    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------------
-- Table: invoice_receipts  (one receipt per successful payment)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.invoice_receipts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_number  TEXT NOT NULL UNIQUE,
    invoice_id      BIGINT NOT NULL REFERENCES public.invoices(id) ON DELETE RESTRICT,
    payment_id      BIGINT NOT NULL REFERENCES public.invoice_payments(id) ON DELETE RESTRICT,
    client_id       UUID NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,

    amount          NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    currency        TEXT NOT NULL DEFAULT 'USD',

    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

