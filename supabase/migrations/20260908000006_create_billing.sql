-- ---------------------------------------------------------------------------
-- Helper: recalculate an invoice's totals from its line items
-- Called server-side after any item mutation
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.recalculate_invoice_totals(p_invoice_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    v_subtotal      NUMERIC(14,2);
    v_tax_rate      NUMERIC(6,4);
    v_tax_amount    NUMERIC(14,2);
    v_discount      NUMERIC(14,2);
    v_total         NUMERIC(14,2);
BEGIN
    -- Recalculate each line_total
    UPDATE public.invoice_items
    SET line_total = ROUND(quantity * unit_price, 2)
    WHERE invoice_id = p_invoice_id;

    -- Sum subtotal
    SELECT COALESCE(SUM(line_total), 0)
    INTO v_subtotal
    FROM public.invoice_items
    WHERE invoice_id = p_invoice_id;

    -- Fetch current tax_rate and discount from invoice
    SELECT tax_rate, discount_amount
    INTO v_tax_rate, v_discount
    FROM public.invoices
    WHERE id = p_invoice_id;

    v_tax_amount := ROUND(v_subtotal * v_tax_rate, 2);
    v_total      := GREATEST(0, v_subtotal + v_tax_amount - v_discount);

    UPDATE public.invoices
    SET subtotal   = v_subtotal,
        tax_amount = v_tax_amount,
        total      = v_total,
        updated_at = NOW()
    WHERE id = p_invoice_id;
END;
$$;

-- ---------------------------------------------------------------------------
-- Helper: mark overdue invoices (run periodically / on list fetch)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.mark_overdue_invoices()
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE updated_count INTEGER;
BEGIN
    UPDATE public.invoices
    SET status     = 'overdue',
        updated_at = NOW()
    WHERE status IN ('sent', 'pending_payment', 'partially_paid')
      AND due_date < CURRENT_DATE
      AND balance_due > 0;

    GET DIAGNOSTICS updated_count = ROW_COUNT;
    RETURN updated_count;
END;
$$;
